/**
 * Adapter that converts a DeskItem or ChairItem into CartVerse's standard Product type
 * so it can be added to cart and processed through checkout seamlessly.
 */
export const toCartProduct = (item: DeskItem | ChairItem, category: 'table' | 'chair'): Product => {
  const isDesk = category === 'table';
  const desk = isDesk ? (item as DeskItem) : null;
  const chair = !isDesk ? (item as ChairItem) : null;

  return {
    id: item.id,
    sku: item.sku,
    name: item.name,
    brand: item.brand,
    category: isDesk ? 'table' : 'chair',
    subcategory: isDesk ? desk?.deskType : chair?.chairType,
    price: item.price,
    originalPrice: item.originalPrice,
    imageSlug: item.imageSlug,
    stock: 12,
    rating: 4.8,
    reviewsCount: 38,
    specs: {
      formFactor: isDesk ? desk?.dimensions : chair?.materials,
      features: isDesk ? desk?.features : [chair?.lumbarTech || '', chair?.armrests || ''],
      powerDraw: 0,
      notes: isDesk ? desk?.targetRig : chair?.mechanism,
    } as any,
    featured: true,
    description: isDesk
      ? `${desk?.name} featuring ${desk?.materials} with ${desk?.maxLoadKg} kg load capacity. Ideal for: ${desk?.targetRig}.`
      : `${chair?.name} with ${chair?.materials}, ${chair?.lumbarTech}, and ${chair?.mechanism}. Max load: ${chair?.maxLoadKg} kg.`,
  };
};
