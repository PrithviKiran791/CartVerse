"use client";
import { useScroll, useTransform } from "framer-motion";
import { useRef } from "react";
import { motion } from "framer-motion";

import { cn } from "@/lib/utils";

export const ParallaxScroll = ({
  images,
  className,
}: {
  images: string[];
  className?: string;
}) => {
  const gridRef = useRef<HTMLDivElement>(null);
  const { scrollYProgress } = useScroll({
    container: gridRef,
    offset: ["start start", "end start"],
  });

  const translateFirst = useTransform(scrollYProgress, [0, 1], [0, -200]);
  const translateSecond = useTransform(scrollYProgress, [0, 1], [0, 200]);
  const translateThird = useTransform(scrollYProgress, [0, 1], [0, -200]);

  const third = Math.ceil(images.length / 3);

  const firstPart = images.slice(0, third);
  const secondPart = images.slice(third, 2 * third);
  const thirdPart = images.slice(2 * third);

  return (
    <div
      className={cn("h-[40rem] items-start overflow-y-auto w-full custom-scrollbar", className)}
      ref={gridRef}
    >
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 items-start max-w-5xl mx-auto gap-10 py-20 px-6 sm:px-10">
        <div className="grid gap-10">
          {firstPart.map((el, idx) => (
            <motion.div
              style={{ y: translateFirst }}
              key={"grid-1-" + idx}
            >
              <img
                src={el}
                className="h-80 w-full object-cover object-center rounded-xl shadow-lg border border-neutral-800/80 gap-10 !m-0 !p-0 transition-transform duration-300 hover:scale-[1.02]"
                height="400"
                width="400"
                alt={"parallax-item-1-" + idx}
                loading="lazy"
              />
            </motion.div>
          ))}
        </div>
        <div className="grid gap-10">
          {secondPart.map((el, idx) => (
            <motion.div
              style={{ y: translateSecond }}
              key={"grid-2-" + idx}
            >
              <img
                src={el}
                className="h-80 w-full object-cover object-center rounded-xl shadow-lg border border-neutral-800/80 gap-10 !m-0 !p-0 transition-transform duration-300 hover:scale-[1.02]"
                height="400"
                width="400"
                alt={"parallax-item-2-" + idx}
                loading="lazy"
              />
            </motion.div>
          ))}
        </div>
        <div className="grid gap-10">
          {thirdPart.map((el, idx) => (
            <motion.div
              style={{ y: translateThird }}
              key={"grid-3-" + idx}
            >
              <img
                src={el}
                className="h-80 w-full object-cover object-center rounded-xl shadow-lg border border-neutral-800/80 gap-10 !m-0 !p-0 transition-transform duration-300 hover:scale-[1.02]"
                height="400"
                width="400"
                alt={"parallax-item-3-" + idx}
                loading="lazy"
              />
            </motion.div>
          ))}
        </div>
      </div>
    </div>
  );
};

